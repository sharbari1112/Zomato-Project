/**
 * Write app/ui/web/assets/config.js from API_BASE (Vercel env).
 * Usage: node scripts/write-api-config.js
 */
const fs = require("fs");
const path = require("path");

const apiBase = String(process.env.API_BASE || "")
  .trim()
  .replace(/\/$/, "");

const outPath = path.join(
  __dirname,
  "..",
  "app",
  "ui",
  "web",
  "assets",
  "config.js",
);

const contents = `/** Generated by scripts/write-api-config.js — do not edit on Vercel builds. */
window.__API_BASE__ = ${JSON.stringify(apiBase)};
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, contents, "utf8");
console.log(`Wrote ${outPath} with __API_BASE__=${JSON.stringify(apiBase)}`);
